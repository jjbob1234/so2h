// A reference to a scene from either game. `index` is MM's native `SceneId` when
// origin == SCENE_ORIGIN_MM, or `SceneIdOot` (this file) when origin == SCENE_ORIGIN_OOT.
// Use this instead of a raw scene id int anywhere both games' scenes need to be
// referred to interchangeably (Map/Quest dual pages, world-swap logic).
typedef struct CompatSceneRef {
    /* 0x0 */ SceneOrigin origin;
    /* 0x4 */ s16 index;
} CompatSceneRef;

static inline CompatSceneRef Scene_RefMm(s16 mmSceneId) {
    CompatSceneRef ref;
    ref.origin = SCENE_ORIGIN_MM;
    ref.index = mmSceneId;
    return ref;
}

static inline CompatSceneRef Scene_RefOot(s16 ootSceneId) {
    CompatSceneRef ref;
    ref.origin = SCENE_ORIGIN_OOT;
    ref.index = ootSceneId;
    return ref;
}

static inline bool Scene_RefIsOot(CompatSceneRef ref) {
    return ref.origin == SCENE_ORIGIN_OOT;
}

