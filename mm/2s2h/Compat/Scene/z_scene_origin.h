/**
 * so2h [Scene] patch 0003 - scene-origin (OOT/MM) tagging system.
 *
 * See /home/user/ProjectZ/env/so2h/patches/0003_scene_origin_tagging.md for full design
 * rationale. Summary of the key decision this file implements:
 *
 * OOT's ~110 scenes are deliberately NOT appended into MM's native `SceneId` enum /
 * `gSceneTable[SCENE_MAX]` numeric space, because three real MM structures are sized/
 * typed for MM's own scene count only and would silently overflow or need a save-
 * format change to extend safely (confirmed by direct read this session):
 *   - `SaveInfo.permanentSceneFlags[120]` and `SaveContext.cycleSceneFlags[120]`
 *     (z64save.h) - fixed-size 120-entry arrays; MM's SCENE_MAX is already 113, only
 *     7 slack slots. +110 OOT scenes would overflow persisted save data.
 *   - `EntranceTableEntry.sceneId` (z64scene.h) is `s8` (max 127); MM's SCENE_MAX=113
 *     leaves only 14 slack values.
 *
 * Instead, OOT scenes get their own independent 0-based `SceneIdOot` enum (this file,
 * mechanically generated by tools/gen_scene_origin.py from reference/soh's real scene
 * table - never hand-transcribed, same rationale as STRICTRULES.md rule 20). Any code
 * that needs to refer to "a scene from either game" uses the `CompatSceneRef` tagged
 * union below instead of a single raw int, and any OOT-specific persisted per-scene
 * data (flags, visited state) must get its own appropriately-sized storage under
 * `ShipSaveInfo` (z64save.h) - never packed into MM's own fixed-size arrays.
 *
 * Confirmed collision: `SCENE_LOST_WOODS` exists in both games' native scene tables
 * (fitting, since Lost Woods is the planned world-swap connector location per the
 * OOT-in-MM design). so2h's OOT scene enum values are namespaced `SCENE_OOT_*`
 * throughout to avoid any ambiguity with MM's own `SCENE_LOST_WOODS`.
 */

